CREATE TABLE fac_major_hazard (
    id                    BIGINT PRIMARY KEY,
    name                  VARCHAR(128),
    level                 VARCHAR(8),
    r_value               DOUBLE,
    monitor_count         INT,
    video_count           INT,
    enterprise            VARCHAR(64),
    category              VARCHAR(32),
    code                  VARCHAR(32),
    longitude             DOUBLE,
    latitude              DOUBLE,
    commission_date       VARCHAR(32),
    key_process           BOOLEAN,
    in_chemical_park      BOOLEAN,
    contacts_json         VARCHAR(4000),
    files_json            VARCHAR(4000),
    monitors_json         VARCHAR(4000),
    videos_json           VARCHAR(4000),
    chemicals_json        VARCHAR(4000),
    evacuation_routes_json VARCHAR(4000),
    operations_json       VARCHAR(4000)
);

CREATE TABLE fac_monitoring_point (
    id         VARCHAR(32) PRIMARY KEY,
    name       VARCHAR(128),
    category   VARCHAR(32),
    status     VARCHAR(16),
    last_time  VARCHAR(32),
    org        VARCHAR(64),
    longitude  DOUBLE,
    latitude   DOUBLE
);

CREATE TABLE fac_monitoring_alarm (
    id    VARCHAR(32) PRIMARY KEY,
    title VARCHAR(128),
    detail VARCHAR(256),
    area  VARCHAR(64),
    time  VARCHAR(32),
    level VARCHAR(16)
);

CREATE TABLE fac_facility_detail (
    facility_name      VARCHAR(128) PRIMARY KEY,
    hazard_source_code VARCHAR(32),
    basic_fields_json  VARCHAR(4000),
    chemical_fields_json VARCHAR(4000),
    archives_json      VARCHAR(4000)
);

