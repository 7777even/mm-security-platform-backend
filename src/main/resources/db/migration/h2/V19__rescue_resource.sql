-- 数据来源：frontend-scaffold/src/screen/lib/data/ 下 rescueEquipmentMock.ts、rescuePersonnelMock.ts、
-- rescueVehicleMock.ts、fireBrigadeMock.ts 的存量硬编码，按 mock 中 buildItem / buildSampleVehicle /
-- buildTeam 的生成规则展开为具体行，迁移后数值与文案语义保持不变。
-- 命名回避数据库保留字（value/command/group/count/status/type/level/left/top）：
--   KV 的取数列为 value_text；人员分组列为 person_group；计数列为 item_count / member_count；
--   状态列统一加域前缀（equipment_status / vehicle_status / equip_status）。
-- 筛选下拉项（中队 / 岗位 / 车辆类型 / 区域）一并入库 fac_rescue_option，含“全部”首项。
-- 种子规模：装备 35 条、人员 52 条、车辆 12 条（含乘员/随车装备/耗材/出动汇总子表）、消防队伍 8 条
-- （含队伍车辆 39 条、队伍人员 110 条、队伍装备 71 条）。

CREATE TABLE fac_rescue_equipment (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    equip_name VARCHAR(64) NOT NULL,
    squadron VARCHAR(32) NOT NULL,
    quantity INT NOT NULL DEFAULT 0,
    leader_name VARCHAR(32) NOT NULL,
    leader_phone VARCHAR(32) NOT NULL,
    stock_quantity INT NOT NULL DEFAULT 0,
    equip_model VARCHAR(128) NOT NULL,
    protection_type VARCHAR(128),
    filter_canister VARCHAR(64),
    max_continuous_use VARCHAR(64),
    storage_location VARCHAR(128),
    purchase_batch VARCHAR(64),
    factory_validity_years VARCHAR(32),
    remaining_validity VARCHAR(32),
    last_inspection_date VARCHAR(32),
    next_mandatory_maintenance_date VARCHAR(32),
    equipment_status VARCHAR(32),
    scrap_warning VARCHAR(32),
    issue_registration VARCHAR(128),
    spare_parts VARCHAR(128),
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_rescue_personnel (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    person_name VARCHAR(32) NOT NULL,
    squadron VARCHAR(32) NOT NULL,
    person_role VARCHAR(32) NOT NULL,
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_rescue_option (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    option_kind VARCHAR(32) NOT NULL,
    option_label VARCHAR(64) NOT NULL,
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_rescue_vehicle (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    plate VARCHAR(32) NOT NULL,
    vehicle_type VARCHAR(32) NOT NULL,
    squadron VARCHAR(32) NOT NULL,
    leader_name VARCHAR(32) NOT NULL,
    leader_phone VARCHAR(32) NOT NULL,
    vehicle_status VARCHAR(16) NOT NULL,
    business_name VARCHAR(64) NOT NULL,
    vehicle_type_full VARCHAR(64) NOT NULL,
    parking_location VARCHAR(128),
    chassis_model VARCHAR(64),
    manufacture_date VARCHAR(32),
    inspection_expiry VARCHAR(32),
    foam_tank_volume VARCHAR(32),
    water_tank_volume VARCHAR(32),
    max_water_flow VARCHAR(32),
    foam_type VARCHAR(32),
    last_maintenance_date VARCHAR(32),
    next_maintenance_date VARCHAR(32),
    total_mileage VARCHAR(32),
    fault_record VARCHAR(128),
    inspection_status VARCHAR(32),
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_rescue_vehicle_crew (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    member_role VARCHAR(32) NOT NULL,
    member_name VARCHAR(32) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    certificate VARCHAR(128),
    duty_status VARCHAR(32),
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_rescue_vehicle_equipment (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    equip_name VARCHAR(64) NOT NULL,
    quantity VARCHAR(32) NOT NULL,
    equip_model VARCHAR(64),
    next_check_date VARCHAR(32),
    equipment_status VARCHAR(32),
    storage_location VARCHAR(128),
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_rescue_vehicle_kv (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    kv_kind VARCHAR(32) NOT NULL,
    kv_label VARCHAR(64) NOT NULL,
    value_text VARCHAR(128) NOT NULL,
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_brigade_team (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    team_name VARCHAR(64) NOT NULL,
    area VARCHAR(32) NOT NULL,
    member_count INT NOT NULL DEFAULT 0,
    leader_name VARCHAR(32) NOT NULL,
    leader_phone VARCHAR(32) NOT NULL,
    location VARCHAR(128),
    longitude DOUBLE,
    latitude DOUBLE,
    description VARCHAR(512),
    rescue_personnel INT NOT NULL DEFAULT 0,
    rescue_vehicles INT NOT NULL DEFAULT 0,
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_brigade_vehicle (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    team_id BIGINT NOT NULL,
    plate VARCHAR(32) NOT NULL,
    vehicle_type VARCHAR(32) NOT NULL,
    vehicle_status VARCHAR(16) NOT NULL,
    parking_location VARCHAR(64),
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_brigade_person (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    team_id BIGINT NOT NULL,
    person_name VARCHAR(32) NOT NULL,
    person_role VARCHAR(32) NOT NULL,
    person_group VARCHAR(32) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    duty_status VARCHAR(16) NOT NULL,
    sort_no INT NOT NULL DEFAULT 0
);

CREATE TABLE fac_brigade_equipment (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    team_id BIGINT NOT NULL,
    equip_name VARCHAR(64) NOT NULL,
    category VARCHAR(32) NOT NULL,
    item_count INT NOT NULL DEFAULT 0,
    unit VARCHAR(16),
    equip_status VARCHAR(16),
    storage_location VARCHAR(64),
    sort_no INT NOT NULL DEFAULT 0
);

